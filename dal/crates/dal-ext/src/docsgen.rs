//! Deterministic generator for embedded dal and Dalgona manuals.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt;
use std::fs;
use std::io::{self, Write};
use std::path::{Path, PathBuf};

/// Product namespace used in page URIs and generator diagnostics.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Scheme {
    /// The dal manual (`dal://`).
    Dal,
    /// The Dalgona manual (`dalgona://`).
    Dalgona,
}

impl Scheme {
    pub(crate) fn uri(self) -> &'static str {
        match self {
            Self::Dal => "dal",
            Self::Dalgona => "dalgona",
        }
    }

    pub(crate) fn prefix(self) -> &'static str {
        match self {
            Self::Dal => "dal-docs",
            Self::Dalgona => "dalgona-docs",
        }
    }
}

/// Inputs for one deterministic manual generation.
#[derive(Clone, Debug)]
pub struct GenArgs {
    /// Manual tree holding `pages` and Markdown files.
    pub dir: PathBuf,
    /// Optional port tree; each child becomes an `examples/` page.
    pub examples: Option<PathBuf>,
    /// Roots scanned for source ownership and page links.
    pub scan: Vec<PathBuf>,
    /// URI scheme used by the generated pages.
    pub scheme: Scheme,
}

/// One generator error with a stable ordering key and rendered diagnostic.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct GenError {
    path: PathBuf,
    line: usize,
    message: String,
}

impl GenError {
    pub(crate) fn new(path: impl Into<PathBuf>, line: usize, message: String) -> Self {
        Self {
            path: path.into(),
            line,
            message,
        }
    }
}

impl fmt::Display for GenError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(&self.message)
    }
}

impl std::error::Error for GenError {}

#[derive(Clone, Debug)]
struct PageSpec {
    name: String,
    owner: String,
    max_lines: usize,
    line: usize,
}

/// Generates the complete Rust module for one manual.
///
/// Reads without following symlinks, normalizes CRLF, checks budgets, and
/// emits pages in byte order.
///
/// # Errors
/// Returns all errors in stable file and line order.
pub fn generate(args: &GenArgs) -> Result<String, Vec<GenError>> {
    let mut errors = Vec::new();
    let prefix = args.scheme.prefix();
    let list_path = args.dir.join("pages");
    let specs = read_specs(args, &mut errors);
    let listed: BTreeMap<_, _> = specs
        .iter()
        .map(|spec| (spec.name.as_str(), spec))
        .collect();
    let mut pages = read_manual(args, &mut errors);
    let manual_pages: BTreeSet<_> = pages.keys().cloned().collect();
    if let Some(examples) = &args.examples {
        pages.extend(assemble_examples(args, examples, &listed, &mut errors));
    }
    check_specs(args, &specs, &pages, &mut errors);
    for name in &manual_pages {
        if !listed.contains_key(name.as_str()) {
            let path = args.dir.join(format!("{name}.md"));
            errors.push(GenError::new(
                &path,
                0,
                format!(
                    "{prefix}: {} is not listed in {}. Add a line \"{name} <readers> <owner> <max-lines>\", or delete the file.",
                    path.display(),
                    list_path.display()
                ),
            ));
        }
    }
    for (name, text) in &pages {
        if let Some(spec) = listed.get(name.as_str()) {
            check_page(args, spec, text, &mut errors);
        }
    }
    check_links(args, &pages, &mut errors);
    let total: usize = pages.values().map(String::len).sum();
    if total > 1_048_576 {
        errors.push(GenError::new(
            &args.dir,
            0,
            format!(
                "{prefix}: the {}:// pages hold {total} bytes; the limit is 1048576.",
                args.scheme.uri()
            ),
        ));
    }
    if !errors.is_empty() {
        errors.sort_by(|a, b| {
            a.path
                .cmp(&b.path)
                .then(a.line.cmp(&b.line))
                .then(a.message.cmp(&b.message))
        });
        return Err(errors);
    }
    let mut out = String::from(
        "// @generated by docs-gen. Do not edit.\npub(crate) static PAGES: &[(&str, &str)] = &[\n",
    );
    for (name, text) in pages {
        out.push_str("    (");
        let _ = std::fmt::Write::write_fmt(&mut out, format_args!("{name:?}, {text:?}"));
        out.push_str("),\n");
    }
    out.push_str("];\n");
    Ok(out)
}

fn parse_spec_line(
    args: &GenArgs,
    path: &Path,
    fields: &[&str],
    no: usize,
    seen: &mut BTreeSet<String>,
    specs: &mut Vec<PageSpec>,
    errors: &mut Vec<GenError>,
) {
    let prefix = args.scheme.prefix();
    let f = fields;
    if f.len() != 4 {
        errors.push(GenError::new(
            path,
            no,
            format!(
                "{prefix}: {}:{no}: expected \"<page> <readers> <owner> <max-lines>\".",
                path.display()
            ),
        ));
        return;
    }
    if !page_valid(f[0]) {
        errors.push(GenError::new(
            path,
            no,
            format!(
                "{prefix}: {}:{no}: \"{}\" is not a page name. Use lowercase letters, digits, and hyphens, with / between parts.",
                path.display(),
                f[0]
            ),
        ));
        return;
    }
    if !seen.insert(f[0].to_owned()) {
        errors.push(GenError::new(
            path,
            no,
            format!(
                "{prefix}: {}:{no}: {}://{} is listed twice.",
                path.display(),
                args.scheme.uri(),
                f[0]
            ),
        ));
        return;
    }
    check_spec_readers(path, prefix, f[1], no, errors);
    if !owner_token_valid(f[2]) {
        errors.push(GenError::new(
            path,
            no,
            format!(
                "{prefix}: {}:{no}: owner \"{}\" is not a valid owner name.",
                path.display(),
                f[2]
            ),
        ));
    }
    match f[3].parse::<usize>() {
        Ok(n) if (1..=1500).contains(&n) => specs.push(PageSpec {
            name: f[0].to_owned(),
            owner: f[2].to_owned(),
            max_lines: n,
            line: no,
        }),
        _ => errors.push(GenError::new(
            path,
            no,
            format!(
                "{prefix}: {}:{no}: max-lines must be from 1 to 1500.",
                path.display()
            ),
        )),
    }
}

fn check_spec_readers(
    path: &Path,
    prefix: &str,
    readers: &str,
    no: usize,
    errors: &mut Vec<GenError>,
) {
    for reader in readers.split(',') {
        if !matches!(
            reader,
            "user" | "model" | "author" | "integrator" | "maintainer"
        ) {
            errors.push(GenError::new(
                path,
                no,
                format!(
                    "{prefix}: {}:{no}: unknown reader \"{reader}\". Use user, model, author, integrator, or maintainer.",
                    path.display()
                ),
            ));
        }
    }
}

fn read_specs(args: &GenArgs, errors: &mut Vec<GenError>) -> Vec<PageSpec> {
    let path = args.dir.join("pages");
    let prefix = args.scheme.prefix();
    let Some(text) = read_text(&path, prefix, errors) else {
        return Vec::new();
    };
    let mut specs = Vec::new();
    let mut seen = BTreeSet::new();
    let mut has_line = false;
    for (index, line) in text.lines().enumerate() {
        let fields: Vec<_> = line.split_whitespace().collect();
        if fields.is_empty() {
            continue;
        }
        has_line = true;
        parse_spec_line(
            args,
            &path,
            &fields,
            index + 1,
            &mut seen,
            &mut specs,
            errors,
        );
    }
    if !has_line {
        errors.push(GenError::new(
            &path,
            0,
            format!("{prefix}: {}: the page list is empty.", path.display()),
        ));
    }
    specs
}

fn assemble_port(
    args: &GenArgs,
    root: &Path,
    entry: &str,
    listed: &BTreeMap<&str, &PageSpec>,
    errors: &mut Vec<GenError>,
) -> Option<(String, String)> {
    let prefix = args.scheme.prefix();
    let dir = root.join(entry);
    let meta = read_metadata(&dir, prefix, errors)?;
    if !meta.is_dir() {
        errors.push(GenError::new(
            &dir,
            0,
            format!(
                "{prefix}: {}: only plugin directories may live here.",
                dir.display()
            ),
        ));
        return None;
    }
    if entry.contains('/') || !page_valid(entry) {
        errors.push(GenError::new(
            &dir,
            0,
            format!(
                "{prefix}: {}: the file name is not a page name. Use lowercase letters, digits, and hyphens.",
                dir.display()
            ),
        ));
        return None;
    }
    let readme = dir.join("README.md");
    let plugin = dir.join("plugin.star");
    let has_readme = read_metadata(&readme, prefix, errors).is_some_and(|m| m.is_file());
    let has_plugin = read_metadata(&plugin, prefix, errors).is_some_and(|m| m.is_file());
    if !has_readme {
        errors.push(GenError::new(
            &dir,
            0,
            format!("{prefix}: {}: README.md is missing.", dir.display()),
        ));
    }
    if !has_plugin {
        errors.push(GenError::new(
            &dir,
            0,
            format!("{prefix}: {}: plugin.star is missing.", dir.display()),
        ));
    }
    if !(has_readme && has_plugin) {
        return None;
    }
    let readme_text = read_text(&readme, prefix, errors)?;
    let mut files = Vec::new();
    collect_port_files(&dir, &mut files, prefix, errors);
    files.retain(|path| path != &readme);
    files.sort_by_key(|path| relative_name(&dir, path));
    let mut text = readme_text;
    text.push_str("\n## Files\n");
    for file in files {
        let Some(content) = read_text(&file, prefix, errors) else {
            continue;
        };
        let fence = "`".repeat(longest_backticks(&content).saturating_add(1).max(3));
        text.push_str("\n### ");
        text.push_str(&relative_name(&dir, &file));
        text.push_str("\n\n");
        text.push_str(&fence);
        text.push_str(language_tag(&file));
        text.push('\n');
        text.push_str(&content);
        if !text.ends_with('\n') {
            text.push('\n');
        }
        text.push_str(&fence);
        text.push('\n');
    }
    let name = format!("examples/{entry}");
    if !listed.contains_key(name.as_str()) {
        let path = args.dir.join(format!("{name}.md"));
        errors.push(GenError::new(
            &path,
            0,
            format!(
                "{prefix}: {} is not listed in {}. Add a line \"{name} <readers> <owner> <max-lines>\", or delete the file.",
                path.display(),
                args.dir.join("pages").display()
            ),
        ));
    }
    Some((name, text))
}

fn owner_token_valid(owner: &str) -> bool {
    let mut bytes = owner.bytes();
    matches!(bytes.next(), Some(b'a'..=b'z'))
        && bytes.all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-')
}

fn owner_exists(owner: &str, scheme: Scheme, manual_dir: &Path, scan: &[PathBuf]) -> bool {
    let under = |sub: &str| scan.iter().any(|root| root.join(sub).is_dir());
    let dal = || {
        SCAN_DAL
            .iter()
            .any(|(token, sub)| *token == owner && under(sub))
            || (owner == "docs"
                && scan
                    .iter()
                    .any(|root| root == manual_dir || root.join("docs") == *manual_dir))
    };
    let dalgona = || {
        SCAN_DALGONA
            .iter()
            .any(|(token, sub)| *token == owner && under(sub))
            || (owner == "docs"
                && scan
                    .iter()
                    .any(|root| root == manual_dir || root.join("docs") == *manual_dir))
    };
    match scheme {
        Scheme::Dal => dal(),
        Scheme::Dalgona => dalgona(),
    }
}

