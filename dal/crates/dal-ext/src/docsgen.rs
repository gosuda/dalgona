fn check_specs(
    args: &GenArgs,
    specs: &[PageSpec],
    pages: &BTreeMap<String, String>,
    errors: &mut Vec<GenError>,
) {
    let prefix = args.scheme.prefix();
    let list_path = args.dir.join("pages");
    for spec in specs {
        if !owner_exists(&spec.owner, args.scheme, &args.dir, &args.scan) {
            errors.push(GenError::new(
                &list_path,
                spec.line,
                format!(
                    "{prefix}: {}:{}: owner {} has no source under the scanned directories.",
                    list_path.display(),
                    spec.line,
                    spec.owner
                ),
            ));
        }
        if pages.contains_key(&spec.name) {
            continue;
        }
        if let Some(example) = spec.name.strip_prefix("examples/") {
            let root = args.examples.as_deref().unwrap_or(Path::new("examples"));
            errors.push(GenError::new(
                &list_path,
                spec.line,
                format!(
                    "{prefix}: {} lists {}://{}, but {}/{} does not exist.",
                    list_path.display(),
                    args.scheme.uri(),
                    spec.name,
                    root.display(),
                    example
                ),
            ));
        } else {
            let path = args.dir.join(format!("{}.md", spec.name));
            errors.push(GenError::new(
                &path,
                0,
                format!(
                    "{prefix}: {} lists {}://{}, but {} does not exist.",
                    list_path.display(),
                    args.scheme.uri(),
                    spec.name,
                    path.display()
                ),
            ));
        }
    }
}

fn read_manual(args: &GenArgs, errors: &mut Vec<GenError>) -> BTreeMap<String, String> {
    let mut pages = BTreeMap::new();
    let prefix = args.scheme.prefix();
    let entries = match read_sorted(&args.dir) {
        Ok(entries) => entries,
        Err(error) => {
            errors.push(GenError::new(
                &args.dir,
                0,
                format!("{prefix}: {}: {error}", args.dir.display()),
            ));
            return pages;
        }
    };
    for entry in entries {
        let path = args.dir.join(&entry);
        if entry == "pages" {
            continue;
        }
        if !entry.to_ascii_lowercase().ends_with(".md") {
            errors.push(GenError::new(
                &path,
                0,
                format!(
                    "{prefix}: {}: only .md files and the pages list may live here.",
                    path.display()
                ),
            ));
            continue;
        }
        let name = entry.trim_end_matches(".md");
        if name.contains('/') || !page_valid(name) {
            errors.push(GenError::new(
                 &path,
                 0,
                 format!(
                     "{prefix}: {}: the file name is not a page name. Use lowercase letters, digits, and hyphens.",
                     path.display()
                 ),
             ));
            continue;
        }
        if let Some(text) = read_text(&path, prefix, errors) {
            pages.insert(name.to_owned(), text);
        }
    }
    pages
}

fn assemble_examples(
    args: &GenArgs,
    root: &Path,
    listed: &BTreeMap<&str, &PageSpec>,
    errors: &mut Vec<GenError>,
) -> BTreeMap<String, String> {
    let prefix = args.scheme.prefix();
    let mut pages = BTreeMap::new();
    let entries = match read_sorted(root) {
        Ok(entries) => entries,
        Err(error) => {
            errors.push(GenError::new(
                root,
                0,
                format!("{prefix}: {}: {error}", root.display()),
            ));
            return pages;
        }
    };
    for entry in entries {
        if let Some((name, text)) = assemble_port(args, root, &entry, listed, errors) {
            pages.insert(name, text);
        }
    }
    pages
}

fn collect_port_files(
    current: &Path,
    files: &mut Vec<PathBuf>,
    prefix: &str,
    errors: &mut Vec<GenError>,
) {
    let entries = match read_sorted(current) {
        Ok(entries) => entries,
        Err(error) => {
            errors.push(GenError::new(
                current,
                0,
                format!("{prefix}: {}: {error}", current.display()),
            ));
            return;
        }
    };
    for entry in entries {
        let path = current.join(entry);
        let Some(meta) = read_metadata(&path, prefix, errors) else {
            continue;
        };
        if meta.is_dir() {
            collect_port_files(&path, files, prefix, errors);
        } else if meta.is_file() {
            files.push(path);
        }
    }
}

fn read_metadata(path: &Path, prefix: &str, errors: &mut Vec<GenError>) -> Option<fs::Metadata> {
    match fs::symlink_metadata(path) {
        Ok(meta) if meta.file_type().is_symlink() => {
            errors.push(GenError::new(
                path,
                0,
                format!(
                    "{prefix}: {}: symbolic links are not allowed.",
                    path.display()
                ),
            ));
            None
        }
        Ok(meta) => Some(meta),
        Err(error) => {
            errors.push(GenError::new(
                path,
                0,
                format!("{prefix}: {}: {error}", path.display()),
            ));
            None
        }
    }
}

fn read_sorted(path: &Path) -> io::Result<Vec<String>> {
    let mut entries = fs::read_dir(path)?
        .map(|entry| entry.map(|entry| entry.file_name()))
        .collect::<Result<Vec<_>, _>>()?;
    entries.sort_by(|a, b| a.as_encoded_bytes().cmp(b.as_encoded_bytes()));
    Ok(entries
        .into_iter()
        .map(|entry| entry.to_string_lossy().into_owned())
        .collect())
}

fn read_text(path: &Path, prefix: &str, errors: &mut Vec<GenError>) -> Option<String> {
    let meta = read_metadata(path, prefix, errors)?;
    if !meta.is_file() {
        errors.push(GenError::new(
            path,
            0,
            format!("{prefix}: {}: expected a regular file.", path.display()),
        ));
        return None;
    }
    match fs::read(path) {
        Ok(bytes) => match std::str::from_utf8(&bytes) {
            Ok(text) => Some(text.replace("\r\n", "\n")),
            Err(error) => {
                errors.push(GenError::new(
                    path,
                    0,
                    format!(
                        "{prefix}: {}: not valid UTF-8 at byte {}.",
                        path.display(),
                        error.valid_up_to()
                    ),
                ));
                None
            }
        },
        Err(error) => {
            errors.push(GenError::new(
                path,
                0,
                format!("{prefix}: {}: {error}", path.display()),
            ));
            None
        }
    }
}

fn relative_name(root: &Path, path: &Path) -> String {
    path.strip_prefix(root)
        .unwrap_or(path)
        .components()
        .map(|part| part.as_os_str().to_string_lossy())
        .collect::<Vec<_>>()
        .join("/")
}

fn language_tag(path: &Path) -> &'static str {
    let tag = path.extension().and_then(|extension| extension.to_str());
    if tag.is_some_and(|tag| tag.eq_ignore_ascii_case("star")) {
        "starlark"
    } else if tag.is_some_and(|tag| tag.eq_ignore_ascii_case("md")) {
        "markdown"
    } else if tag.is_some_and(|tag| tag.eq_ignore_ascii_case("toml")) {
        "toml"
    } else if tag.is_some_and(|tag| tag.eq_ignore_ascii_case("rs")) {
        "rust"
    } else {
        ""
    }
}

fn longest_backticks(text: &str) -> usize {
    text.as_bytes()
        .split(|byte| *byte != b'`')
        .map(<[u8]>::len)
        .max()
        .unwrap_or(0)
}

fn page_path(args: &GenArgs, page: &str) -> PathBuf {
    if let Some(name) = page.strip_prefix("examples/") {
        args.examples
            .as_deref()
            .unwrap_or(Path::new("examples"))
            .join(name)
    } else {
        args.dir.join(format!("{page}.md"))
    }
}

fn check_page(args: &GenArgs, spec: &PageSpec, text: &str, errors: &mut Vec<GenError>) {
    let path = page_path(args, &spec.name);
    let prefix = args.scheme.prefix();
    let lines = text.lines().count();
    if text.len() > 49_152 {
        errors.push(GenError::new(
            &path,
            0,
            format!(
                "{prefix}: {}: {} bytes; the limit is 49152. Split the page.",
                path.display(),
                text.len()
            ),
        ));
    }
    if lines > 1500 {
        errors.push(GenError::new(
            &path,
            0,
            format!(
                "{prefix}: {}: {lines} lines; the limit is 1500. Split the page.",
                path.display()
            ),
        ));
    }
    if lines > spec.max_lines {
        errors.push(GenError::new(
            &path,
            0,
            format!(
                "{prefix}: {}: {lines} lines; {} allows {}.",
                path.display(),
                args.dir.join("pages").display(),
                spec.max_lines
            ),
        ));
    }
    let title = text.lines().next().unwrap_or_default().strip_prefix("# ");
    if !title.is_some_and(|title| !title.is_empty() && title.len() <= 80) {
        errors.push(GenError::new(
            &path,
            1,
            format!(
                "{prefix}: {}:1: the first line must be \"# \" and a title of 1 to 80 bytes.",
                path.display()
            ),
        ));
    }
}

fn check_links(args: &GenArgs, pages: &BTreeMap<String, String>, errors: &mut Vec<GenError>) {
    let prefix = args.scheme.prefix();
    let scheme = args.scheme.uri();
    let mut files = BTreeSet::<PathBuf>::new();
    for root in &args.scan {
        collect_scan_files(root, &mut files);
    }
    for page in pages.keys() {
        if !page.starts_with("examples/") {
            files.insert(args.dir.join(format!("{page}.md")));
        }
    }
    for path in files {
        let Some(text) = read_text(&path, prefix, errors) else {
            continue;
        };
        for (index, line) in text.lines().enumerate() {
            for page in own_scheme_links(line, scheme) {
                if page.is_empty() || page == "index" || page.ends_with('/') {
                    continue;
                }
                if !page_valid(&page) || !pages.contains_key(&page) {
                    errors.push(GenError::new(
                        &path,
                        index + 1,
                        format!(
                            "{prefix}: {}:{}: {scheme}://{page} is not a page.",
                            path.display(),
                            index + 1
                        ),
                    ));
                }
            }
        }
    }
}

fn collect_scan_files(current: &Path, files: &mut BTreeSet<PathBuf>) {
    let Ok(entries) = read_sorted(current) else {
        return;
    };
    for entry in entries {
        let path = current.join(entry);
        let Ok(meta) = fs::symlink_metadata(&path) else {
            continue;
        };
        if meta.file_type().is_symlink() {
            continue;
        }
        if meta.is_dir() {
            let Some(name) = path.file_name().and_then(|name| name.to_str()) else {
                continue;
            };
            if name == "target" || name.starts_with('.') {
                continue;
            }
            collect_scan_files(&path, files);
        } else if meta.is_file() && scannable(&path) {
            files.insert(path);
        }
    }
}

fn scannable(path: &Path) -> bool {
    path.extension()
        .and_then(|extension| extension.to_str())
        .is_some_and(|extension| {
            extension.eq_ignore_ascii_case("rs")
                || extension.eq_ignore_ascii_case("md")
                || extension.eq_ignore_ascii_case("star")
        })
}

fn own_scheme_links(line: &str, scheme: &str) -> Vec<String> {
    let bytes = line.as_bytes();
    let marker = b"://";
    let scheme_bytes = scheme.as_bytes();
    let mut found = Vec::new();
    let mut cursor = 0;
    while cursor + marker.len() <= bytes.len() {
        let Some(relative) = line[cursor..].find("://") else {
            break;
        };
        let separator = cursor + relative;
        let start = separator.saturating_sub(scheme_bytes.len());
        let before = start
            .checked_sub(1)
            .and_then(|index| bytes.get(index))
            .copied();
        if start + scheme_bytes.len() <= separator
            && &bytes[start..separator] == scheme_bytes
            && !before.is_some_and(|byte| byte.is_ascii_alphanumeric() || byte == b'_')
        {
            let page_start = separator + marker.len();
            let mut end = page_start;
            while end < bytes.len()
                && !bytes[end].is_ascii_whitespace()
                && !matches!(
                    bytes[end],
                    b'`' | b'<'
                        | b'>'
                        | b'"'
                        | b'\''
                        | b'('
                        | b')'
                        | b'['
                        | b']'
                        | b'{'
                        | b'}'
                        | b'|'
                )
            {
                end += 1;
            }
            let mut page = String::from_utf8_lossy(&bytes[page_start..end]).into_owned();
            while matches!(
                page.as_bytes().last(),
                Some(b'.' | b',' | b';' | b'!' | b'?' | b':')
            ) {
                page.pop();
            }
            found.push(page);
        }
        cursor = separator + marker.len();
    }
    found
}

/// Returns whether `page` matches the lowercase, slash-separated page grammar.
#[must_use]
pub fn page_valid(page: &str) -> bool {
    if page.is_empty() {
        return false;
    }
    page.split('/').all(|segment| {
        let mut bytes = segment.bytes();
        matches!(bytes.next(), Some(b'a'..=b'z' | b'0'..=b'9'))
            && bytes.all(|byte| byte.is_ascii_lowercase() || byte.is_ascii_digit() || byte == b'-')
    })
}

/// Runs the command-line interface used by the `docs-gen` binary.
///
/// # Errors
/// Returns 0 on success, 1 for manual validation errors, and 2 for invalid
/// arguments or output failures.
#[must_use]
pub fn cli<I: Iterator<Item = String>>(mut args: I) -> i32 {
    let _program = args.next();
    let mut scheme = None;
    let mut dir = None;
    let mut examples = None;
    let mut scan = Vec::new();
    let mut out = None;
    let mut argument_error = None;
    while let Some(flag) = args.next() {
        let Some(value) = args.next() else {
            argument_error = Some(format!("missing value for {flag}"));
            break;
        };
        match flag.as_str() {
            "--scheme" => scheme = Some(value),
            "--dir" => dir = Some(PathBuf::from(value)),
            "--examples" => examples = Some(PathBuf::from(value)),
            "--scan" => scan.push(PathBuf::from(value)),
            "--out" => out = Some(PathBuf::from(value)),
            _ => {
                argument_error = Some(format!("unknown argument {flag}"));
                break;
            }
        }
    }
    let parsed = match scheme.as_deref() {
        Some("dal") => Some(Scheme::Dal),
        Some("dalgona") => Some(Scheme::Dalgona),
        Some(value) => {
            argument_error = Some(format!("unknown scheme {value}"));
            None
        }
        None => {
            argument_error = Some("missing --scheme".to_owned());
            None
        }
    };
    let Some(scheme) = parsed else {
        return cli_error(
            "dal-docs",
            &argument_error.unwrap_or_else(|| "invalid arguments".to_owned()),
        );
    };
    let (Some(dir), Some(out)) = (dir, out) else {
        return cli_error(scheme.prefix(), "missing --dir or --out");
    };
    if let Some(error) = argument_error {
        return cli_error(scheme.prefix(), &error);
    }
    match generate(&GenArgs {
        dir,
        examples,
        scan,
        scheme,
    }) {
        Ok(module) => match fs::write(out, module) {
            Ok(()) => 0,
            Err(error) => cli_error(scheme.prefix(), &format!("cannot write output: {error}")),
        },
        Err(errors) => {
            let mut stderr = io::stderr().lock();
            for error in errors {
                let _ = writeln!(stderr, "{error}");
            }
            1
        }
    }
}

fn cli_error(prefix: &str, message: &str) -> i32 {
    let _ = writeln!(io::stderr().lock(), "{prefix}: {message}");
    2
}
