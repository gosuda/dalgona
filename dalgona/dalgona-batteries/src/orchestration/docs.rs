//! The `dalgona://agents`, `dalgona://workflows`, and `dalgona://goal`
//! manual pages. Each page states the facts section 4 of the behavior
//! contract fixes: the tool actions, the limits, the report tool, the
//! delivery rule, and the goal lifecycle.

/// Manual page text registered under `dalgona://agents`.
pub const AGENTS_DOC: &str = concat!(
    "# Agents\n\n",
    "Run subagents in the background. `agents` takes one `action`:\n\n",
    "- `run` starts a workflow and returns at once. A workflow is a list of steps. ",
    "A step without `items` is one subagent (a task). A step with `items` is a pool: ",
    "one subagent per item, at most `workers` at a time (default 4, range 1 to 64). ",
    "A step with `after` starts when those steps end. The other actions are `wait`, ",
    "`cancel`, and `list`.\n",
    "- `wait` blocks until runs or tasks end. `timeout` is seconds to wait at most, ",
    "default 60, at most 600.\n",
    "- `cancel` stops runs or tasks and their descendants.\n",
    "- `list` shows runs, providers, and saved workflows: at most 20 runs, ",
    "200 task lines per run, then it says how to read the full report.\n\n",
    "## Placeholders\n\n",
    "`{{item}}` is the item of a pool. `{{step:<name>}}` is the reports of a step ",
    "listed in `after`. `{{input}}` is the input of a saved workflow. ",
    "There is no escape for `{{`; a different placeholder is an error. ",
    "A pool prompt must contain `{{item}}`; a task must not.\n\n",
    "## Tools and approval\n\n",
    "Subagents see only the tools you list, by default `read` and `search`, at most 16 names. ",
    "They cannot ask the user: `patch` works only in approval modes `edits` and `all`, ",
    "and `exec` only in `all`. A step that lists `patch` or `exec` runs in its own git ",
    "worktree by default, and its changes merge back when it ends done. ",
    "Subagents cannot start subagents, hold a goal, or call `/abort`; `agents`, ",
    "`create_goal`, `update_goal`, `get_goal`, and `monitor` are refused as step tools.\n\n",
    "## Report and the one last turn\n\n",
    "Each subagent ends by calling its own `orchestration__report` tool exactly once, ",
    "with status `done`, `blocked`, or `failed` and 1 to 16,000 characters of report text. ",
    "An empty report is refused, and a second report cannot replace the first. ",
    "When a subagent never reports, it gets one final grace turn of 60 seconds; ",
    "if it stays silent it fails with `no report after the last turn`.\n\n",
    "## Delivery\n\n",
    "You get one message per run, not one per subagent. Reports are held and delivered ",
    "at request boundaries, only when the session is ready: after 2 seconds of quiet, ",
    "16 waiting reports, or one report waiting 60 seconds. A wake that reached the ",
    "session is never repeated: only its acknowledgement is retried. ",
    "Full reports stay one read away at `job://<id>`.\n\n",
    "## Limits\n\n",
    "1 to 32 steps per run; step names `[a-z][a-z0-9-]{0,31}`, unique; prompts 1 to ",
    "32,000 characters; pool items 1 to 1024, each 1 to 2,000 characters; `after` up to ",
    "31 steps; tools at most 16 names. Run labels at most 80 bytes. `max_runs` defaults ",
    "to 16 under `[plugin.orchestration.agents]` (1 to 64); `child_max_steps` defaults ",
    "to 50 (1 to 1000); `child_max_minutes` defaults to 30 (1 to 600); a session starts ",
    "at most 1024 subagents (`agents_per_session` has a fixed ceiling of 1024). ",
    "Isolation is `worktree` or `shared`; worktree needs git 2.17 or newer and refuses ",
    "to start when git is missing or the checkout is not a repository.\n",
);

/// Manual page text registered under `dalgona://workflows`.
pub const WORKFLOWS_DOC: &str = concat!(
    "# Workflows\n\n",
    "A saved workflow is one table under `[plugin.orchestration.workflows.<name>]` ",
    "in config. It holds an optional `description` (at most 200 characters) and ",
    "`steps` — the same steps an inline `agents run` takes.\n\n",
    "## Shape\n\n",
    "```toml\n",
    "[plugin.orchestration.workflows.audit-routes]\n",
    "description = \"Audit route handlers for missing auth checks.\"\n\n",
    "[[plugin.orchestration.workflows.audit-routes.steps]]\n",
    "name = \"find\"\n",
    "prompt = \"List every HTTP route handler file under src/. Put one path per line in your report and nothing else.\"\n\n",
    "[[plugin.orchestration.workflows.audit-routes.steps]]\n",
    "name = \"audit\"\n",
    "after = [\"find\"]\n",
    "items_from = \"find\"\n",
    "workers = 8\n",
    "prompt = \"Check {{item}} for route handlers that skip the auth check. {{input}}\"\n",
    "```\n\n",
    "`items_from` names one earlier task step in `after`: the step becomes a pool over ",
    "the non-empty lines of that step's report, each cut to 2,000 characters, at most ",
    "1,024 lines. `{{input}}` needs input: run the saved workflow with `input`, or the ",
    "run is refused.\n\n",
    "## Refusals\n\n",
    "An invalid workflow is refused with the exact reason: unknown or missing fields, ",
    "a name that does not match `[a-z][a-z0-9-]{0,31}` or is used twice, a prompt ",
    "outside 1 to 32,000 characters, `items` and `items_from` together, `items` outside ",
    "1 to 1024 items of 1 to 2,000 characters, `workers` on a task or outside 1 to 64, ",
    "`after` naming a missing step or forming a cycle, `items_from` not in `after` or ",
    "naming a pool, a pool prompt without `{{item}}`, `{{item}}` in a task, ",
    "`{{step:<name>}}` without the name in `after`, `{{input}}` without input, ",
    "an unknown `{{...}}` placeholder, or a tool list over 16 names. ",
    "A step tool naming `agents`, `report`, `create_goal`, `update_goal`, `get_goal`, ",
    "or `monitor` is refused: `agents: step <name>: tool <tool> is not for subagents.`\n\n",
    "A saved workflow that does not decode is not a startup error. Running it says ",
    "`agents: saved workflow \"<name>\" is invalid: <reason>. Fix [plugin.orchestration.workflows.<name>] in config.` ",
    "An unknown name says `agents: no saved workflow \"<name>\".` and lists the known names. ",
    "A saved workflow with `{{input}}` and no input is refused until input is given.\n",
);

/// Manual page text registered under `dalgona://goal`.
pub const GOAL_DOC: &str = concat!(
    "# Goal\n\n",
    "A goal is one durable objective for the session. The model manages it through ",
    "`create_goal`, `update_goal`, and `get_goal`; you manage it through `/goal`.\n\n",
    "## Commands\n\n",
    "`/goal <objective>` creates or replaces the goal. `/goal` shows it. ",
    "`/goal pause` pauses continuations, `/goal resume` resumes them, and ",
    "`/goal clear` removes the goal. `create_goal` fails while an unfinished goal ",
    "exists; `update_goal` moves the status to `paused`, `blocked`, or `complete`.\n\n",
    "## Objective\n\n",
    "The objective is 1 to 4,000 characters. A longer one is refused, never truncated: ",
    "put the full objective in a file and name the file in the objective.\n\n",
    "## Continuations\n\n",
    "While a goal is active, the battery continues it automatically: right after an ",
    "automatic turn, ten seconds after a turn you started, and at idle wakes. ",
    "Continuations stop on their own when the work ends, and every continuation counts ",
    "against guards you can raise with `/goal pause` or `/continuation pause`:\n\n",
    "- 8 consecutive continuations on one progress signature block with ",
    "`continuation cap reached`;\n",
    "- 150 continuations without a message from you block with ",
    "`unattended continuation limit reached`;\n",
    "- three identical outputs in a row block with `repeated assistant output`;\n",
    "- a second output-truncation stop after one recovery blocks with ",
    "`output truncation repeated`;\n",
    "- a turn that ended on a provider error blocks with ",
    "`provider error ended the turn (retries exhausted)`.\n\n",
    "A message from you resets the consecutive count, and a paused or blocked goal ",
    "continues when you speak again. `/continuation run` starts automatic turns; ",
    "`/continuation pause` and `/continuation stop` stop them. The last mode survives ",
    "the session in the goal sidecar.\n\n",
    "## Storage\n\n",
    "A goal lives in `goal.json` beside the session and only for a saved session: ",
    "an ephemeral session refuses goals. Reopening the session restores the goal, ",
    "its counters, and the last controller mode. A damaged goal file arms nothing; ",
    "only `/goal clear` replaces it.\n",
);

